_COMPILED: dict = {}


def _compile_all() -> None:
    if _COMPILED:
        return
    for intent, by_lang in _RAW_PATTERNS.items():
        _COMPILED[intent] = {}
        for lang, patterns in by_lang.items():
            compiled = []
            for p in patterns:
                try:
                    compiled.append(re.compile(p, re.IGNORECASE | re.UNICODE))
                except re.error:
                    continue
                if p.endswith(r"\b"):
                    try:
                        compiled.append(re.compile(p[:-2], re.IGNORECASE | re.UNICODE))
                    except re.error:
                        pass
            _COMPILED[intent][lang] = compiled


def patterns_for(intent: str, language: str) -> list:
    _compile_all()
    by_lang = _COMPILED.get(intent, {})
    return by_lang.get(language) or by_lang.get("en") or []


def all_intents() -> list:
    return list(_RAW_PATTERNS.keys())


def all_languages_for(intent: str) -> list:
    return list(_RAW_PATTERNS.get(intent, {}).keys())